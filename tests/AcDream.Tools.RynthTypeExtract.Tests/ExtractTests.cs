using AcDream.Tools.RynthTypeExtract;

namespace AcDream.Tools.RynthTypeExtract.Tests;

public sealed class ExtractTests
{
    private const string Panel = """
        // header
        using System.Text.Json.Serialization;
        using Avalonia;
        using Avalonia.Controls;

        namespace Their.Panels;

        [JsonSerializable(typeof(ThingPanel.Payload))]
        internal partial class ThingPanelJsonContext : JsonSerializerContext { }

        internal static class ThingPanel
        {
            private static readonly IBrush Teal = new SolidColorBrush();

            internal sealed class Payload
            {
                [JsonPropertyName("rows")] public List<Row> Rows { get; set; } = new();
            }

            internal sealed class Row { public string Name { get; set; } = ""; }

            private sealed class State { public Payload Data = new(); }

            public static Control Create() => new Border();
        }

        internal sealed class ThingView : UserControl { }
        """;

    [Fact]
    public void KeepsTheNamedTypesAndTheJsonContextsTextUnchanged()
    {
        string text = Program.Extract(Panel, "ThingPanel", ["Payload", "Row"], "ThingPanel.cs");

        Assert.Contains("""[JsonPropertyName("rows")] public List<Row> Rows { get; set; } = new();""", text, StringComparison.Ordinal);
        Assert.Contains("internal sealed class Row { public string Name { get; set; } = \"\"; }", text, StringComparison.Ordinal);
        Assert.Contains("internal partial class ThingPanelJsonContext : JsonSerializerContext { }", text, StringComparison.Ordinal);
        Assert.Contains("using System.Text.Json.Serialization;", text, StringComparison.Ordinal);
        Assert.Contains("namespace Their.Panels;", text, StringComparison.Ordinal);
        Assert.DoesNotContain("Avalonia", text, StringComparison.Ordinal);
        Assert.DoesNotContain("State", text, StringComparison.Ordinal);
        Assert.DoesNotContain("Create", text, StringComparison.Ordinal);
        Assert.DoesNotContain("Teal", text, StringComparison.Ordinal);
        Assert.DoesNotContain("ThingView", text, StringComparison.Ordinal);
        Assert.StartsWith("// <auto-generated>", text, StringComparison.Ordinal);
    }

    [Fact]
    public void WithNoContainerKeepsTheNamedTopLevelTypes()
    {
        string text = Program.Extract(Panel, "", ["ThingView"], "ThingPanel.cs");

        Assert.Contains("internal sealed class ThingView : UserControl { }", text, StringComparison.Ordinal);
        Assert.DoesNotContain("ThingPanelJsonContext", text, StringComparison.Ordinal);
        Assert.DoesNotContain("class ThingPanel", text, StringComparison.Ordinal);
        Assert.DoesNotContain("using Avalonia", text, StringComparison.Ordinal);
        Assert.ThrowsAny<Exception>(() => Program.Extract(Panel, "", ["Payload"], "ThingPanel.cs"));
    }

    [Fact]
    public void ATypeTheContainerLacksFailsTheRun()
    {
        string dir = Directory.CreateTempSubdirectory("rynth-extract-").FullName;
        try
        {
            string source = Path.Combine(dir, "ThingPanel.cs"), output = Path.Combine(dir, "out.cs");
            File.WriteAllText(source, Panel);
            var error = new StringWriter();

            int code = Program.Run([source, output, "ThingPanel=Payload,Missing"], TextWriter.Null, error);

            Assert.Equal(1, code);
            Assert.Contains("ThingPanel has no nested type Missing", error.ToString(), StringComparison.Ordinal);
            Assert.False(File.Exists(output));
        }
        finally { Directory.Delete(dir, true); }
    }

    [Fact]
    public void AnUnchangedRunLeavesTheOutputAlone()
    {
        string dir = Directory.CreateTempSubdirectory("rynth-extract-").FullName;
        try
        {
            string source = Path.Combine(dir, "ThingPanel.cs"), output = Path.Combine(dir, "out.cs");
            File.WriteAllText(source, Panel);
            Assert.Equal(0, Program.Run([source, output, "ThingPanel=Payload,Row"], TextWriter.Null, TextWriter.Null));
            var written = new DateTime(2020, 1, 1, 0, 0, 0, DateTimeKind.Utc);
            File.SetLastWriteTimeUtc(output, written);

            Assert.Equal(0, Program.Run([source, output, "ThingPanel=Payload,Row"], TextWriter.Null, TextWriter.Null));

            Assert.Equal(written, File.GetLastWriteTimeUtc(output));
        }
        finally { Directory.Delete(dir, true); }
    }

    [Fact]
    public void ABadCommandLinePrintsUsage()
    {
        var error = new StringWriter();
        Assert.Equal(2, Program.Run(["a.cs", "b.cs", "NoTypes"], TextWriter.Null, error));
        Assert.Equal(2, Program.Run(["a.cs", "b.cs", "Container="], TextWriter.Null, TextWriter.Null));
        Assert.StartsWith("usage:", error.ToString(), StringComparison.Ordinal);
    }
}
