using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace AcDream.Tools.RynthTypeExtract;

/// <summary>
/// <c>AcDream.Tools.RynthTypeExtract &lt;source.cs&gt; &lt;output.cs&gt; &lt;Container&gt;=&lt;Type,...&gt;</c>:
/// writes the source file again with only what the named nested types need:
/// the container class keeps those nested types and nothing else, every
/// other top-level type goes except the file's <c>JsonSerializerContext</c>
/// classes (they name the kept types), and <c>using Avalonia…</c> directives
/// go. What stays is their text, unchanged. A named type the container lacks,
/// or a container the file lacks, fails the run. The output is only
/// rewritten when its text changes, so an unchanged run doesn't recompile.
/// </summary>
internal static class Program
{
    private const string Usage = "usage: AcDream.Tools.RynthTypeExtract <source.cs> <output.cs> <Container>=<Type,...>";

    private static int Main(string[] args) => Run(args, Console.Out, Console.Error);

    /// <summary>The command line, with its output and error streams given (tests capture them).</summary>
    internal static int Run(string[] args, TextWriter output, TextWriter error)
    {
        if (args.Length != 3 || args[2].Split('=') is not [{ Length: > 0 } container, { Length: > 0 } list])
        {
            error.WriteLine(Usage);
            return 2;
        }

        string[] keep = list.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        try
        {
            string text = Extract(File.ReadAllText(args[0]), container, keep, Path.GetFileName(args[0]));
            if (!File.Exists(args[1]) || File.ReadAllText(args[1]) != text)
                File.WriteAllText(args[1], text);
            output.WriteLine($"RynthTypeExtract: {Path.GetFileName(args[0])}: {container}.{{{string.Join(", ", keep)}}}");
            return 0;
        }
        catch (Exception ex) when (ex is ExtractException or IOException)
        {
            error.WriteLine($"RynthTypeExtract: {Path.GetFileName(args[0])}: {ex.Message}");
            return 1;
        }
    }

    /// <summary>The source with only <paramref name="container"/>'s <paramref name="keep"/> types and the JSON contexts.</summary>
    internal static string Extract(string source, string container, IReadOnlyCollection<string> keep, string sourceName)
    {
        var root = (CompilationUnitSyntax)CSharpSyntaxTree.ParseText(source).GetRoot();

        List<TypeDeclarationSyntax> containers = root.DescendantNodes().OfType<TypeDeclarationSyntax>()
            .Where(t => t.Identifier.Text == container && t.Parent is BaseNamespaceDeclarationSyntax or CompilationUnitSyntax)
            .ToList();
        if (containers.Count != 1)
            throw new ExtractException($"expected one top-level type {container}, found {containers.Count}");

        TypeDeclarationSyntax found = containers[0];
        var nested = found.Members.OfType<TypeDeclarationSyntax>().Where(t => keep.Contains(t.Identifier.Text)).ToList();
        string[] missing = keep.Where(k => !nested.Any(t => t.Identifier.Text == k)).ToArray();
        if (missing.Length > 0)
            throw new ExtractException($"{container} has no nested type {string.Join(", ", missing)}");

        var drop = new List<SyntaxNode>();
        drop.AddRange(found.Members.Where(m => !nested.Contains(m)));
        drop.AddRange(root.DescendantNodes().OfType<UsingDirectiveSyntax>()
            .Where(u => u.Name?.ToString() is { } name && (name == "Avalonia" || name.StartsWith("Avalonia.", StringComparison.Ordinal))));
        drop.AddRange(root.DescendantNodes().OfType<BaseTypeDeclarationSyntax>()
            .Where(t => t.Parent is BaseNamespaceDeclarationSyntax or CompilationUnitSyntax && t != found && !IsJsonContext(t)));

        SyntaxNode trimmed = root.RemoveNodes(drop, SyntaxRemoveOptions.KeepNoTrivia)!;
        return $"// <auto-generated>\n// Extracted from RynthCore's {sourceName} by RynthTypeExtract: {container}.{{{string.Join(", ", keep)}}}\n// and the file's JSON contexts, their text unchanged. Do not edit.\n// </auto-generated>\n"
            + trimmed.ToFullString();
    }

    private static bool IsJsonContext(BaseTypeDeclarationSyntax type) =>
        type.BaseList?.Types.Any(b => b.Type.ToString() is "JsonSerializerContext" or "System.Text.Json.Serialization.JsonSerializerContext") == true;

    private sealed class ExtractException(string message) : Exception(message);
}
